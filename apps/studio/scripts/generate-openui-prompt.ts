/**
 * Compiles the OpenUI component library into the Agent's answer contract.
 *
 * Mirrors the official shadcn-chat example: the library that renders the answer
 * in the browser is the same library that generates the prompt, so the taught
 * signatures and the rendered components cannot drift. It runs as a script
 * rather than on the server so the Agent bundle stays free of React.
 *
 * Two prompts are emitted by `compileAnswerPrompts`: a read-only contract that
 * teaches `relation_preview`, and a read-write contract that adds the governed
 * `database_action` tool. The host picks between them from the live access mode,
 * so a read-only Studio never teaches a write tool.
 *
 * Run with `bun run generate:openui-prompt`; `dev` and `build` run it first.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { compileAnswerPrompts } from "../src/generative/openui-answer-prompt";

const output = join(import.meta.dir, "../src/generative/openui-system-prompt.generated.ts");
const { base, actions } = compileAnswerPrompts();

const banner = [
  "// Generated by scripts/generate-openui-prompt.ts — do not edit by hand.",
  "// Source of truth: src/client/components/generative/shadcn-genui.",
  "",
].join("\n");

writeFileSync(
  output,
  `${banner}export const OPENUI_SYSTEM_PROMPT = ${JSON.stringify(base)};\n\n`
    + `export const OPENUI_ACTION_SYSTEM_PROMPT = ${JSON.stringify(actions)};\n`,
);

console.log(`Wrote ${output} (base ${base.length} chars, actions ${actions.length} chars).`);
